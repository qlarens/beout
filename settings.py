# --- завершение ---
# Нет новых точек столько времени — тренировку закрываем (сел телефон, пропала сеть).
# Меньше не ставить: на долгой остановке Telegram может молчать, и конец тренировки потеряется.
STALE_AFTER_S = 2 * 3600

# --- калории: MET × вес × часы в движении ---
DEFAULT_WEIGHT = 75.0

# --- совместные тренировки и рейтинги ---
# Столько после создания к совместной тренировке можно присоединиться,
# и новые тренировки участников привязываются к ней.
SESSION_TTL_S = 12 * 3600
# Рейтинг группы: сколько мест на тип; итоги прошлой недели постятся в понедельник в этот час (UTC).
RATING_TOP_N = 10
RATING_POST_HOUR_UTC = 8

# --- набор высоты ---
# В геопозиции Telegram высоты нет: берём по координатам у Open-Meteo (бесплатно, без ключа).
